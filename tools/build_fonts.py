"""Bundle the app's fonts locally so it works offline.

Usage: python3 tools/build_fonts.py <@fontsource/klee-one package dir> <@fontsource/zen-kaku-gothic-new package dir> <app dir>

Copies the woff2 files into fonts/ and writes css/fonts.css. Klee One gets every subset
(Japanese included) because it renders all kana and kanji; Zen Kaku Gothic New only
needs Latin for the English interface.
"""
import os, re, shutil, sys

klee, zen, app = sys.argv[1:4]
out_dir = os.path.join(app, 'fonts')
os.makedirs(out_dir, exist_ok=True)
rules = []
face_re = re.compile(r'@font-face\s*{[^}]*}', re.S)
src_re = re.compile(r"url\(\./files/([^)]+?\.woff2)\)")


def take(pkg, css_names, keep=lambda f: True):
    for name in css_names:
        css = open(os.path.join(pkg, name), encoding='utf-8').read()
        for face in face_re.findall(css):
            m = src_re.search(face)
            if not m or not keep(m.group(1)):
                continue
            fn = m.group(1)
            shutil.copy(os.path.join(pkg, 'files', fn), os.path.join(out_dir, fn))
            face = re.sub(r'src:[^;]+;', f"src: url(../fonts/{fn}) format('woff2');", face)
            rules.append(face)


take(klee, ['400.css', '600.css'])
take(zen, ['400.css', '500.css', '700.css'], keep=lambda f: '-latin-' in f)
for pkg, name in ((klee, 'KleeOne'), (zen, 'ZenKakuGothicNew')):
    shutil.copy(os.path.join(pkg, 'LICENSE'), os.path.join(out_dir, f'{name}-OFL.txt'))

with open(os.path.join(app, 'css', 'fonts.css'), 'w', encoding='utf-8') as f:
    f.write('/* Klee One and Zen Kaku Gothic New, SIL Open Font License 1.1 (see fonts/*-OFL.txt).\n'
            '   Generated by tools/build_fonts.py from the @fontsource packages. */\n')
    f.write('\n'.join(rules) + '\n')
total = sum(os.path.getsize(os.path.join(out_dir, x)) for x in os.listdir(out_dir))
print(len(rules), 'font faces,', round(total / 1e6, 1), 'MB')
